#!/usr/bin/env python3
"""Собирает выписку из документации внешних методов — ДО того, как их подделают.

ЗАЧЕМ (04.08, живой случай). Подделка внешнего клиента в тестах воспроизводила моё
ожидание, а не описанный договор: у telethon `offset_date` документирован как «сообщения
ПРЕДЫДУЩИЕ этой даты», и обратный порядок это переворачивает. Ни тестировщик, ни кодер
документацию не открывали — и не могли: в задании её не было. Тесты зелёные, живой путь
не идёт. Дефект вылез ровно там, где оба честно написали «сюда мы не смотрим».

ПОЧЕМУ СБОРЩИК, А НЕ ПРАВИЛО В ИНСТРУКЦИИ. Правило «проверь документацию» держится на
внимании и умирает так же, как умерли мои --deselect в командной строке: любой, кто не
знал, его не выполнит. Выписка достаётся программно — значит её отсутствие становится
видимым состоянием, а не забытым намерением.

ПРЕДЕЛ, НАЗВАННЫЙ ЗДЕСЬ ЖЕ: выписка НЕ заменяет живой вызов. Документация врёт, отстаёт
и молчит о частностях. Два требования, а не одно вместо другого.

Использование:
    collect_dependency_contract.py telethon.client.messages:MessageMethods.iter_messages [...]
    collect_dependency_contract.py --module telethon.client.messages --attr MessageMethods.iter_messages
"""
import importlib
import inspect
import sys


def resolve(spec):
    """'модуль:Класс.метод' -> объект. Путь пишется явно: угадывание тут дороже."""
    if ":" not in spec:
        raise SystemExit("нужен формат модуль:Класс.метод — %r не разобрать" % spec)
    module_name, path = spec.split(":", 1)
    obj = importlib.import_module(module_name)
    for part in path.split("."):
        obj = getattr(obj, part)
    return obj


def contract(spec):
    obj = resolve(spec)
    doc = inspect.getdoc(obj)
    if not doc:
        # МОЛЧАНИЕ ИСТОЧНИКА — ФАКТ, А НЕ ПУСТОТА: без документации подделку строить
        # нельзя, нужен обратный порядок — сперва живой вызов, потом подделка по записи.
        return ("## %s\n\nДОКУМЕНТАЦИИ НЕТ. Подделку по догадке НЕ писать: сперва живой\n"
                "вызов, записать наблюдаемое поведение, и уже из записи строить подделку.\n" % spec)
    try:
        sig = str(inspect.signature(obj))
    except (TypeError, ValueError):
        sig = "(сигнатура недоступна)"
    return "## %s\n\nСигнатура: %s\n\n```\n%s\n```\n" % (spec, sig, doc)


def main(argv):
    specs = [a for a in argv if not a.startswith("-")]
    if not specs:
        raise SystemExit(__doc__)
    print("# Договор внешних зависимостей (собран автоматически)\n")
    print("Подделка пишется ПО ЭТОМУ ТЕКСТУ, а не по ожиданию. Расхождение подделки с\n"
          "договором — дефект подделки. И даже совпав с договором, подделка остаётся\n"
          "моделью: обязателен один живой вызов до приёмки.\n")
    for spec in specs:
        print(contract(spec))


if __name__ == "__main__":
    main(sys.argv[1:])
