#!/usr/bin/env python3
"""Детектор переводного синтаксиса в русском тексте (промис #20).

ЗАЧЕМ. Словарный лист наблюдения (style_watchlist.py) ловит ШТАМПЫ — повторяющиеся слова.
Но переводной синтаксис живёт не в словаре, а в СТРОЕ фразы: расщеплённое сказуемое,
цепочки родительных, отглагольные конструкции. Запрет слова выдавливает штамп в соседнее
слово, а строй остаётся. Граница названа OpenArt: корень — строй, не словарь.

ЧТО НЕ ДЕЛАЕТ. Не判断ает, плох ли текст: находки — кандидаты, решение за автором. Русский
допускает каждую из этих конструкций; дефектом их делает ПЛОТНОСТЬ, поэтому прибор печатает
долю на 1000 слов, а не список ошибок.
"""
import re, sys, json

RULES = [
    ("расщеплённое сказуемое",
     r"\b(производ\w+|осуществл\w+|выполн\w+|провод\w+|осуществля\w+)\s+\w+(ание|ение|ку|цию|ния)\b",
     "производить проверку → проверять"),

    ("канцелярский предлог",
     r"\b(в целях|в рамках|в течение|по причине|в связи с тем|с целью|в случае если|в результате того)\b",
     "чтобы / из-за / если"),
    ("является + твор. падеж",
     r"\bявля(ется|ются)\s+\w+(ом|ем|ой|ей|ым|им)\b",
     "является причиной → это причина / причиняет"),
    # «данные» (мн.ч., data) намеренно НЕ ловим: на моём корпусе за сутки это дало 34
    # ложных срабатывания из 34 находок. Цена — пропуск «данные обстоятельства»;
    # предел объявлен здесь, а не в отчёте.
    ("данный вместо этот",
     r"\b(данн(ый|ая|ое|ого|ому|ой|ым|ом)|указанн(ый|ая|ое|ые|ого|ой))\b",
     "этот / тот"),
    ("имеет место / носит характер",
     r"\b(имеет место|носит\s+\w+\s+характер|представляет собой)\b",
     "просто назвать действие"),
    ("страдательный залог на -ся при агенте",
     r"\b\w+(ируется|ается|яется)\s+(мной|нами|системой|агентом)\b",
     "я делаю, а не делается мной"),
]


# Односимвольные окончания («и», «а», «я», «ы») убраны: они ловят глаголы и прилагательные
# — «приёмов ПОЛУЧИЛИ условия срабатывания» прибор выдавал за цепочку родительных.
GEN_TAIL = ("ния", "ения", "ости", "ации", "тва", "ства", "ений", "аний", "ров", "лей",
            "ля", "ра", "та", "ки", "ды", "ов", "ей", "ий")
DEVERB = ("ние", "ния", "ение", "ения", "ация", "ации", "ость", "ости", "тва", "ства")


def _gen_chains(text):
    """Цепочки родительных ловятся не регуляркой, а счётом окончаний подряд.

    Регулярка 01.08 не поймала «осуществление контроля выполнения обязательств» —
    ждала одинаковых окончаний у всех трёх слов. Дефект нашёлся негативным тестом на
    эталонном канцелярите, а НЕ чтением кода: на моём корпусе правило молчало, и это
    молчание выглядело как «у меня такого нет».
    """
    out = []
    # Границы предложений обязательны: без них цепочка собирается ЧЕРЕЗ точку и абзац —
    # на моём корпусе так родилось «вариации интерпретации / Ограничительная конечная»,
    # то есть прибор склеивал разные фразы и предъявлял их как одну конструкцию.
    for sent in re.split(r"[.!?;:\n]+", text):
        _chain_in(sent, out)
    return out


def _chain_in(sent, out):
    words = re.findall(r"\b[а-яё]{5,}\b", sent, re.I)
    run = []
    for w in words:
        if w.lower().endswith(GEN_TAIL):
            run.append(w)
        else:
            if len(run) >= 3 and sum(1 for x in run if x.lower().endswith(DEVERB)) >= 2:
                out.append(" ".join(run[:4]))
            run = []
    if len(run) >= 3 and sum(1 for x in run if x.lower().endswith(DEVERB)) >= 2:
        out.append(" ".join(run[:4]))


def scan(text):
    words = len(re.findall(r"\b[а-яёА-ЯЁ]+\b", text)) or 1
    hits = []
    for name, pat, hint in RULES:
        for m in re.finditer(pat, text, re.I):
            hits.append({"rule": name, "hit": m.group(0)[:60], "hint": hint})
    for chain in _gen_chains(text):
        hits.append({"rule": "цепочка родительных (3+)", "hit": chain[:60],
                     "hint": "переставить в глаголы"})
    return {"words": words, "hits": hits,
            "per_1000": round(len(hits) * 1000 / words, 2)}


if __name__ == "__main__":
    src = open(sys.argv[1], encoding="utf-8").read() if len(sys.argv) > 1 else sys.stdin.read()
    r = scan(src)
    print(f"слов {r['words']}, находок {len(r['hits'])}, плотность {r['per_1000']} на 1000 слов")
    seen = {}
    for h in r["hits"]:
        seen.setdefault(h["rule"], []).append(h["hit"])
    for rule, items in sorted(seen.items(), key=lambda kv: -len(kv[1])):
        print(f"  {len(items):>3}× {rule}: {', '.join(items[:3])}")
